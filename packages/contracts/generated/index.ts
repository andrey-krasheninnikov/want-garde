export const PRODUCT_VERSION = "0.1.0-dev.0" as const;
export const CONTRACT_VERSION = "1" as const;
export type Id = string;
export type WireVersion = "1";
export type Action = { "type": "server.status", };
export type OperationRequest = { version: WireVersion, request_id: Id, server_id: Id, action: Action, };
export type ErrorCode = "invalid_request" | "access_denied" | "unavailable" | "conflict" | "audit_unavailable" | "not_implemented" | "internal";
export type ContractError = { code: ErrorCode, message_key: Id, };
export type Severity = "info" | "warning" | "high" | "critical";
export type Classification = { category: Id, severity: Severity, rule_id: Id, reason_key: Id, };
export type Evidence = { name: Id, value: string, };
export type Event = { version: WireVersion, id: Id, server_id: Id, observed_at: string, source: Id, classification: Classification, evidence: Array<Evidence>, };
export type IncidentState = { "type": "open" } | { "type": "acknowledged", by: Id, at: string, } | { "type": "closed", by: Id, at: string, reason: string, };
export type Incident = { version: WireVersion, id: Id, server_id: Id, event_ids: Array<Id>, severity: Severity, state: IncidentState, };
export type Capability = "status.read" | "events.read" | "incidents.read";
export type Scope = { server_id: Id, resource_ids: Array<Id>, allowed_chat_ids: Array<string>, };
export type Grant = { version: WireVersion, principal_id: Id, scope: Scope, capabilities: Array<Capability>, };
export type OperationResult = { "type": "server_status", server_id: Id, product_version: string, };
export type JobState = { "type": "awaiting_approval" } | { "type": "queued" } | { "type": "running" } | { "type": "succeeded", result: OperationResult, } | { "type": "failed", error: ContractError, } | { "type": "cancelled" } | { "type": "timed_out" } | { "type": "needs_reconciliation", reason_key: Id, };
export type Job = { version: WireVersion, id: Id, request_id: Id, server_id: Id, state: JobState, };
